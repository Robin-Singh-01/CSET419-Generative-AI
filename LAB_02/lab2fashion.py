# ==========================================
class RobustClassifier(nn.Module):
    def __init__(self):
        super().__init__()
        # Deeper architecture: 32 -> 64 filters
        self.features = nn.Sequential(
            nn.Conv2d(1, 32, kernel_size=3, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),
            nn.MaxPool2d(2), # 28x28 -> 14x14

            nn.Conv2d(32, 64, kernel_size=3, padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(),
            nn.MaxPool2d(2), # 14x14 -> 7x7
        )
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(64 * 7 * 7, 128),
            nn.ReLU(),
            nn.Dropout(0.5), # Prevents overfitting
            nn.Linear(128, 10)
        )

    def forward(self, x):
        x = self.features(x)
        return self.classifier(x)

def prepare_classifier():
    print("Training robust classifier for evaluation (Wait ~1-2 mins)...")
    clf = RobustClassifier().to(device)
    opt = optim.Adam(clf.parameters(), lr=0.001)
    crit = nn.CrossEntropyLoss()

    # Train for 5 full epochs (instead of partial 1) to ensure high accuracy
    clf.train()
    for epoch in range(10):
        correct = 0
        total = 0
        running_loss = 0.0

        for images, labels in dataloader:
            images, labels = images.to(device), labels.to(device)

            opt.zero_grad()
            outputs = clf(images)
            loss = crit(outputs, labels)
            loss.backward()
            opt.step()

            # Track accuracy
            _, predicted = torch.max(outputs.data, 1)
            total += labels.size(0)
            correct += (predicted == labels).sum().item()
            running_loss += loss.item()

        acc = 100 * correct / total
        print(f"  Classifier Epoch {epoch+1}/10 | Loss: {running_loss/len(dataloader):.4f} | Acc: {acc:.2f}%")

    print("Classifier ready.\n")
    clf.eval()
    return clf

# Replace the old call with this new one
classifier = prepare_classifier()

# 4. GAN ARCHITECTURE
# ==========================================
class Generator(nn.Module):
    def __init__(self, noise_dim):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(noise_dim, 256), nn.LeakyReLU(0.2), nn.BatchNorm1d(256),
            nn.Linear(256, 512), nn.LeakyReLU(0.2), nn.BatchNorm1d(512),
            nn.Linear(512, 1024), nn.LeakyReLU(0.2), nn.BatchNorm1d(1024),
            nn.Linear(1024, 28*28), nn.Tanh()
        )
    def forward(self, x): return self.net(x).view(-1, 1, 28, 28)

class Discriminator(nn.Module):
    def __init__(self):
        super().__init__()
        self.net = nn.Sequential(
            nn.Flatten(),
            nn.Linear(28*28, 512), nn.LeakyReLU(0.2), nn.Dropout(0.3),
            nn.Linear(512, 256), nn.LeakyReLU(0.2), nn.Dropout(0.3),
            nn.Linear(256, 1), nn.Sigmoid()
        )
    def forward(self, x): return self.net(x)

gen = Generator(config['noise_dim']).to(device)
disc = Discriminator().to(device)
opt_g = optim.Adam(gen.parameters(), lr=config['learning_rate'], betas=(0.5, 0.999))
opt_d = optim.Adam(disc.parameters(), lr=config['learning_rate'], betas=(0.5, 0.999))
criterion = nn.BCELoss()

# Helper for Weight Delta
def get_params(model):
    return torch.cat([p.view(-1) for p in model.parameters()]).detach().clone()

# Helper for Visualization
def show_and_save_images(epoch, fixed_noise):
    gen.eval()
    with torch.no_grad():
        fake_imgs = gen(fixed_noise).cpu()

    # Create figure
    fig, axes = plt.subplots(5, 5, figsize=(6, 6))
    plt.suptitle(f"Epoch {epoch}")

    for i, ax in enumerate(axes.flatten()):
        ax.imshow(fake_imgs[i].squeeze(), cmap='gray')
        ax.axis('off')

    # 1. Save to folder
    save_path = f"generated_samples/epoch_{epoch:02d}.png"
    plt.savefig(save_path)

    # 2. Show in notebook/console
    plt.show()

    print(f"Saved image to: {save_path}")
    gen.train()

print(f"\nStarting GAN Training ({config['epochs']} Epochs)...")

for epoch in range(config['epochs']):
    d_loss_sum = 0; g_loss_sum = 0; d_acc_sum = 0
    d_delta_sum = 0; g_delta_sum = 0
    batches = 0

    for real_imgs, _ in dataloader:
        real_imgs = real_imgs.to(device)
        curr_batch = real_imgs.size(0)

        # --- TRAIN D ---
        disc.zero_grad()
        out_real = disc(real_imgs)
        loss_real = criterion(out_real, torch.ones_like(out_real))

        noise = torch.randn(curr_batch, config['noise_dim']).to(device)
        fake_imgs = gen(noise)
        out_fake = disc(fake_imgs.detach())
        loss_fake = criterion(out_fake, torch.zeros_like(out_fake))

        loss_d = (loss_real + loss_fake) / 2
        loss_d.backward()
        p_d_before = get_params(disc)
        opt_d.step()
        p_d_after = get_params(disc)
        d_delta_sum += torch.norm(p_d_after - p_d_before).item()

        d_acc = ((out_real > 0.5).float().mean() + (out_fake < 0.5).float().mean()) / 2

        # --- TRAIN G ---
        gen.zero_grad()
        out_g = disc(fake_imgs)
        loss_g = criterion(out_g, torch.ones_like(out_g))
        loss_g.backward()
        p_g_before = get_params(gen)
        opt_g.step()
        p_g_after = get_params(gen)
        g_delta_sum += torch.norm(p_g_after - p_g_before).item()

        d_loss_sum += loss_d.item(); g_loss_sum += loss_g.item()
        d_acc_sum += d_acc.item(); batches += 1

    # --- LOGS ---
    print(f"Epoch {epoch+1:02d}/{config['epochs']} | "
          f"Loss D: {d_loss_sum/batches:.4f} | D Acc: {100*d_acc_sum/batches:.2f}% | "
          f"Loss G: {g_loss_sum/batches:.4f} | "
          f"D_Delta: {d_delta_sum/batches:.5f} | G_Delta: {g_delta_sum/batches:.5f}")

    # --- SHOW & SAVE ---
    if (epoch + 1) % config['save_interval'] == 0:
        show_and_save_images(epoch+1, fixed_noise)


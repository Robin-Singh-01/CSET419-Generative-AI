# Use GPU if available
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"Using device: {device}")

IMAGE_SIZE = 512 if torch.cuda.is_available() else 256  # smaller on CPU

# Image loader: converts PIL Image → tensor
def load_image(image_path_or_url, size=IMAGE_SIZE):
    transform = transforms.Compose([
        transforms.Resize((size, size)),
        transforms.ToTensor(),
    ])
    if image_path_or_url.startswith("http"):
        response = requests.get(image_path_or_url)
        image = Image.open(BytesIO(response.content)).convert("RGB")
    else:
        image = Image.open(image_path_or_url).convert("RGB")

    # Add batch dimension: (1, C, H, W)
    image = transform(image).unsqueeze(0)
    return image.to(device)

# Tensor → PIL Image for display
def tensor_to_image(tensor):
    image = tensor.cpu().clone().squeeze(0)
    image = image.clamp(0, 1)
    return transforms.ToPILImage()(image)

# Show images side by side
def show_images(content_img, style_img, output_img=None):
    imgs = [("Content", content_img), ("Style", style_img)]
    if output_img is not None:
        imgs.append(("Output (Stylized)", output_img))
    fig, axes = plt.subplots(1, len(imgs), figsize=(6 * len(imgs), 5))
    for ax, (title, img) in zip(axes, imgs):
        ax.imshow(tensor_to_image(img) if not isinstance(img, Image.Image) else img)
        ax.set_title(title, fontsize=14)
        ax.axis("off")
    plt.tight_layout()
    plt.show()

